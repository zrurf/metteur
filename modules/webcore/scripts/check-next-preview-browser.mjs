import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import { mkdirSync, writeFileSync } from 'node:fs'

const output = process.argv[2]
if (!output) throw new Error('An isolated evidence directory is required')
mkdirSync(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1360, height: 1050 }, reducedMotion: 'reduce' })
const errors = []
page.on('pageerror', error => errors.push(error.message))
page.on('request', request => {
  if (!request.url().startsWith('http://127.0.0.1:18974/')) errors.push(`Unexpected network request: ${new URL(request.url()).origin}`)
})
try {
  await page.goto('http://127.0.0.1:18974/?preview=PV-01')
  await page.getByRole('button', { name: 'Pin as convention' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  assert.match(await page.getByRole('status').innerText(), /cancelled/)
  await page.getByRole('button', { name: 'Pin as convention' }).click()
  await page.getByRole('button', { name: 'Confirm convention' }).click()
  assert.match(await page.getByRole('status').innerText(), /revision 3/)
  await page.getByRole('button', { name: 'Edit note' }).click()
  await page.getByLabel('Note body').fill('A new draft requires a new confirmation.')
  await page.getByRole('button', { name: 'Save new revision' }).click()
  assert.match(await page.getByRole('status').innerText(), /no longer applies/)
  await page.getByRole('button', { name: 'Reset fixture' }).click()
  await page.screenshot({ path: `${output}/PV-01-r1-light.png`, fullPage: true })
  await page.getByRole('button', { name: 'Dark theme' }).click()
  await page.getByRole('button', { name: 'Pin as convention' }).click()
  await page.screenshot({ path: `${output}/PV-01-r1-confirm-dark.png`, fullPage: true })
  await page.keyboard.press('Escape')
  // Escape is dispatched within the dialog, matching normal keyboard use.
  if (await page.getByRole('dialog').count()) await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Prompt resources', exact: true }).click()
  await page.getByRole('button', { name: 'Add to Chat', exact: true }).click()
  await page.getByRole('button', { name: 'Personal', exact: true }).click()
  await page.getByRole('button', { name: 'Add to Chat', exact: true }).click()
  await page.getByRole('button', { name: 'Add to blueprint', exact: true }).click()
  assert.equal(await page.getByLabel('Chat drop target', { exact: true }).locator('.pv-chip').count(), 2)
  await page.getByRole('button', { name: 'Send fixture message' }).click()
  assert.match(await page.getByText('Sent history · immutable user content').innerText(), /immutable/)
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByLabel('Prompt body').fill('Edited source; history must stay unchanged.')
  await page.getByRole('button', { name: 'Save revision' }).click()
  assert.match(await page.getByRole('status').innerText(), /sent history is unchanged/)
  await page.getByRole('button', { name: 'Light theme' }).click()
  await page.screenshot({ path: `${output}/PV-02-r1-scopes-history.png`, fullPage: true })
  await page.getByRole('button', { name: 'Reset fixture' }).click()
  await page.getByRole('heading', { name: /Review checklist/ }).dragTo(page.getByLabel('Chat drop target', { exact: true }))
  assert.equal(await page.getByLabel('Chat drop target', { exact: true }).locator('.pv-chip').count(), 1)
  await page.getByRole('heading', { name: /Review checklist/ }).dragTo(page.getByLabel('Blueprint drop target', { exact: true }))
  assert.equal(await page.getByLabel('Blueprint drop target', { exact: true }).locator('.pv-chip').count(), 1)
  await page.getByRole('combobox', { name: 'Scenario' }).selectOption('Changed version')
  await page.getByRole('button', { name: 'Send fixture message' }).click()
  assert.match(await page.getByRole('status').innerText(), /before sending/)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: `${output}/PV-02-r1-narrow.png`, fullPage: true })
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
  assert.deepEqual(errors, [])
  writeFileSync(`${output}/preview-check.json`, JSON.stringify({ passed: true, fixture: 'nx-m1-fixture-1', revisions: { 'PV-01': 1, 'PV-02': 1 }, checks: ['exact revision confirmation and cancellation', 'edit invalidates convention', 'same name scopes', 'immutable sent fixture', 'drag to chat and blueprint', 'changed source blocks send', 'narrow layout', 'no external network or page error'], approval: null }, null, 2))
  console.log('PV-01/r1 and PV-02/r1 directed browser check: PASS; human approval pending')
} finally { await browser.close() }
