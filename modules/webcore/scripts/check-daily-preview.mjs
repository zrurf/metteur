import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import { mkdir, writeFile, readFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'

const output = process.argv[2]
if (!output) throw Error('An evidence directory is required')
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1360, height: 1050 }, reducedMotion: 'reduce' })
page.setDefaultTimeout(6000)
const errors = [], checks = []
page.on('pageerror', e => errors.push(e.message))
page.on('request', r => { if (!r.url().startsWith('http://127.0.0.1:19081/')) errors.push(`Unexpected request: ${new URL(r.url()).origin}`) })
const state = value => page.getByLabel('Fixture State').selectOption(value)
const group = id => page.getByRole('button', { name: new RegExp(`^${id}`) }).click()
try {
  await page.goto('http://127.0.0.1:19081/?preview=WF-PV-01')
  const message = page.getByLabel('Preview Message', {exact:true}), send = page.getByRole('button', { name: 'Send Preview Message' })
  await message.fill('keep original conversation draft')
  await message.dispatchEvent('keydown', { key: 'Enter', isComposing: true, keyCode: 229 })
  assert.equal(await message.inputValue(), 'keep original conversation draft')
  assert.equal(await send.isDisabled(), true)
  await page.getByRole('button', { name: /^Search Investigation/ }).click()
  assert.equal(await message.inputValue(), 'Investigate the search index.')
  await state('Completed')
  assert.match(await page.locator('h1').innerText(), /Search/)
  await page.getByRole('button', { name: /^Validation Repair.*Session A/ }).click()
  assert.equal(await message.inputValue(), 'keep original conversation draft')
  await state('Missing Model')
  await page.getByRole('button', { name: 'Open Supervision' }).click()
  assert.equal(await send.isDisabled(), true)
  assert.match(await page.getByLabel('Preview Message', {exact:true}).inputValue(), /Keep the existing/)
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  assert.match(await page.getByRole('status').innerText(), /Pause confirmed/)
  checks.push('WF-PV-01: original sessions/drafts, blocked send, synthetic IME, no navigation on completion, independent supervision and direct control without model')
  await state('Disconnected')
  await page.getByRole('button', { name: 'Stop', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Stop This Run' }).click()
  assert.match(await page.getByText('Stop outcome unknown').innerText(), /Reconcile/)
  await page.screenshot({ path: `${output}/WF-PV-01-r1-light.png`, fullPage: true })

  await group('WF-PV-02')
  await state('Running')
  const editor = page.getByLabel('Recovery Editor')
  await editor.fill('raw draft\r\nwith incomplete syntax {')
  await page.getByRole('button', { name: 'Back Up Draft' }).click()
  assert.match(await page.locator('.dw-page-header').innerText(), /Backed Up on Host/)
  const ack = await editor.inputValue()
  await editor.fill('newer unacknowledged edit')
  assert.match(await page.locator('.dw-page-header').innerText(), /Not Backed Up/)
  await page.getByRole('button', { name: 'Reopen Confirmed Copy' }).click()
  assert.equal(await editor.inputValue(), ack)
  await page.getByRole('button', { name: 'Simulate External Change' }).click()
  await page.getByRole('button', { name: 'Save Reviewed Content' }).click()
  assert.match(await page.getByRole('status').innerText(), /disk changed again/)
  assert.equal(await page.getByRole('dialog').isVisible(), true)
  await page.getByRole('button', { name: 'Keep Both', exact: true }).click()
  assert.match(await page.getByRole('status').innerText(), /create-only/)
  await page.getByRole('button', { name: 'Reference in Chat' }).click()
  await page.getByRole('button', { name: 'Use Saved Version' }).click()
  assert.equal(await editor.inputValue(), ack)
  await page.getByRole('button', { name: 'Discard Draft', exact: true }).click()
  await page.getByRole('button', { name: 'Keep Editing', exact: true }).click()
  assert.equal(await editor.inputValue(), ack)
  await page.getByRole('tab', { name: 'repair.blueprint' }).click()
  assert.match(await editor.inputValue(), /unfinished edit/)
  await state('Disconnected')
  await page.getByRole('button', { name: 'Back Up Draft' }).click()
  assert.match(await page.getByRole('status').innerText(), /not backed up/)
  checks.push('WF-PV-02: exact snapshot ACK, newer edit unprotected, recovery compare, CAS after external change, create-only keep both, saved reference, discard cancellation, invalid raw draft, offline warning')
  await page.screenshot({ path: `${output}/WF-PV-02-r1-light.png`, fullPage: true })

  await group('WF-PV-03')
  await state('Unknown Effect')
  assert.equal(await page.getByRole('button', { name: 'Resume Execution' }).isDisabled(), true)
  await page.getByRole('button', { name: 'Inspect Reason & Evidence' }).click()
  assert.match(await page.getByRole('dialog').innerText(), /No generic Continue/)
  await page.keyboard.press('Escape')
  await page.getByLabel('Launch Source').selectOption('Editor Direct Run')
  await page.getByRole('button', { name: 'Review Launch' }).click()
  assert.match(await page.getByRole('dialog').innerText(), /Independent run; no source conversation/)
  assert.equal(await page.getByRole('button', { name: 'Confirm This Version' }).isDisabled(), true)
  await page.keyboard.press('Escape')
  await state('Completed')
  await page.getByRole('button', { name: 'Add Result to Draft' }).click()
  assert.match(await page.getByRole('status').innerText(), /Send remains explicit/)
  await page.getByText('Identity, Budget & Unhandled Requests').click()
  assert.match(await page.locator('.dw-details').innerText(), /Actual model calls: 0/)
  await page.screenshot({ path: `${output}/WF-PV-03-r1-light.png`, fullPage: true })
  checks.push('WF-PV-03: unknown effects cannot resume, direct run has no fake session, result only adds source to draft, separate evidence/summary/acceptance, no model calls')

  for (const id of ['WF-PV-01', 'WF-PV-02', 'WF-PV-03']) {
    await group(id)
    for (const width of [1360, 390]) {
      await page.setViewportSize({ width, height: 950 })
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${id} overflows ${width}`)
      await page.getByRole('button', { name: 'Dark Theme', exact: true }).click()
      await page.screenshot({ path: `${output}/${id}-r1-dark-${width}.png`, fullPage: true })
      await page.getByRole('button', { name: 'Light Theme', exact: true }).click()
    }
  }
  assert.deepEqual(errors, [])
  checks.push('All three groups: light/dark, 1360/390px no horizontal overflow, reduced motion, no external network or page errors')
} finally {
  await browser.close()
  const source = await readFile('src/previews/next/daily/DailyPreview.vue')
  await writeFile(`${output}/result.json`, JSON.stringify({ candidate: execFileSync('git', ['rev-parse','HEAD'], {encoding:'utf8'}).trim(), source_status: execFileSync('git',['status','--short'],{encoding:'utf8'}), source_sha256:createHash('sha256').update(source).digest('hex'), revision:'r1',fixture:'dw-fixture-1',mode:'L2 isolated static preview',platform:process.platform,checks,errors,paid_calls:0,user_approval:null }, null, 2))
}
